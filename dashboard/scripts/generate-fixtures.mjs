// Generates src/data/fixtures/ledger.ts: DEMO monthly fee records for a fictional merchant.
// Every figure on the dashboard is calculated from these records, so replacing the fixture with real data
// (same shape) updates the whole app. Run: node scripts/generate-fixtures.mjs
import { writeFileSync } from 'node:fs';

const months = ['2025-11', '2025-12', '2026-01', '2026-02', '2026-03', '2026-04', '2026-05', '2026-06', '2026-07', '2026-08', '2026-09', '2026-10'];
// Monthly card sales ($) and average ticket
const volume = [15.6e6, 19.8e6, 15.1e6, 14.6e6, 15.9e6, 16.0e6, 16.4e6, 16.8e6, 17.2e6, 17.4e6, 17.675e6, 18.4e6];
const txnTarget = [205400, 262100, 199300, 192900, 209800, 210600, 216100, 221000, 226300, 228900, 232790, 248620];

const segments = ['visa_debit', 'mc_debit', 'eftpos_debit', 'visa_credit', 'mc_credit', 'amex_credit'];
// Share of card sales by segment; from Jul the mix drifts toward credit
const baseShare = { visa_debit: 0.32, mc_debit: 0.15, eftpos_debit: 0.18, visa_credit: 0.18, mc_credit: 0.10, amex_credit: 0.07 };
const credit = (s) => s.endsWith('credit');
function shares(i) {
  const drift = Math.max(0, i - 7) * 0.012; // Jul onward
  const out = {};
  for (const s of segments) out[s] = baseShare[s] + (credit(s) ? drift * (s === 'amex_credit' ? 0.25 : 0.375) : -drift / 3);
  return out;
}
const ticketFactor = { visa_debit: 0.85, mc_debit: 0.85, eftpos_debit: 0.8, visa_credit: 1.3, mc_credit: 1.3, amex_credit: 1.6 };

// Pass-through rates (% of value) - demo values, not published scheme rates
const interchangePct = { visa_debit: 0.12, mc_debit: 0.12, eftpos_debit: 0.09, visa_credit: 0.72, mc_credit: 0.72, amex_credit: 0 };
const schemePct = (s, m) => ({ visa_debit: 0.1, mc_debit: 0.1, eftpos_debit: 0.06, visa_credit: 0.4, mc_credit: 0.4, amex_credit: 0 })[s]
  + (m >= '2026-10' && credit(s) && !s.startsWith('amex') ? 0.08 : 0);

// Contracted provider pricing, with the effective dates of notified changes
const contract = {
  A: (m) => ({ acquiringPct: m >= '2026-10' ? 0.58 : m >= '2026-07' ? 0.52 : 0.36, processorCents: m >= '2026-08' ? 12 : 10, monthlyFixed: 18950 }),
  B: (m) => ({ acquiringPct: m >= '2026-08' ? 0.66 : 0.6, processorCents: 18, monthlyFixed: 6800 }),
  C: () => ({ acquiringPct: 1.6, processorCents: 0, monthlyFixed: 450 }),
};
// Charged above contract (the "discrepancies" the audit should find)
function overcharge(p, s, m) {
  const o = { acquiringPct: 0, processorCents: 0 };
  if (p === 'A' && m >= '2026-10' && (s === 'visa_credit' || s === 'mc_credit')) o.acquiringPct = 0.12;
  if (p === 'B' && m >= '2026-09') o.processorCents = 2;
  if (p === 'C' && m >= '2026-10') o.acquiringPct = 0.15;
  return o;
}
const r2 = (x) => Math.round(x * 100) / 100;

const records = [];
months.forEach((m, i) => {
  const sh = shares(i);
  const atv = volume[i] / txnTarget[i];
  const rows = [];
  for (const s of segments) {
    const channels = s === 'amex_credit' ? [['C', 1]] : [['A', 0.72], ['B', 0.28]];
    for (const [p, cs] of channels) rows.push({ p, s, value: volume[i] * sh[s] * cs, rawCount: (volume[i] * sh[s] * cs) / (atv * ticketFactor[s]) });
  }
  const scale = txnTarget[i] / rows.reduce((a, r) => a + r.rawCount, 0);
  let assigned = 0;
  rows.forEach((r, k) => {
    const count = k === rows.length - 1 ? txnTarget[i] - assigned : Math.round(r.rawCount * scale);
    assigned += count;
    const c = contract[r.p](m), o = overcharge(r.p, r.s, m);
    const onlineIc = r.p === 'B' && credit(r.s) ? 0.05 : 0;
    const fixedShare = (r.value / rows.filter((x) => x.p === r.p).reduce((a, x) => a + x.value, 0)) * c.monthlyFixed;
    const expected = {
      acquiring: r2((r.value * c.acquiringPct) / 100), interchange: r2((r.value * (interchangePct[r.s] + onlineIc)) / 100),
      scheme: r2((r.value * schemePct(r.s, m)) / 100), processor: r2((count * c.processorCents) / 100), other: r2(fixedShare),
    };
    const fees = { ...expected,
      acquiring: r2((r.value * (c.acquiringPct + o.acquiringPct)) / 100),
      processor: r2((count * (c.processorCents + o.processorCents)) / 100) };
    records.push({ month: m, provider: r.p, segment: r.s, transactions: count, value: r2(r.value), fees, expected });
  });
});

const body = `// DEMO DATA - generated by scripts/generate-fixtures.mjs for a fictional merchant. Not real fees or rates.
// Replace with real records of the same shape (see src/data/types.ts).
import type { LedgerRecord } from '../types';

export const ledger: LedgerRecord[] = ${JSON.stringify(records, null, 0).replace(/\},\{"month"/g, '},\n  {"month"')};
`;
writeFileSync(new URL('../src/data/fixtures/ledger.ts', import.meta.url), body);
for (const m of months) {
  const rs = records.filter((r) => r.month === m);
  const v = rs.reduce((a, r) => a + r.value, 0), t = rs.reduce((a, r) => a + r.transactions, 0);
  const f = rs.reduce((a, r) => a + Object.values(r.fees).reduce((x, y) => x + y, 0), 0);
  const e = rs.reduce((a, r) => a + Object.values(r.expected).reduce((x, y) => x + y, 0), 0);
  const comp={};for(const r of rs)for(const[k,x]of Object.entries(r.fees))comp[k]=(comp[k]||0)+x;
  console.log(Object.entries(comp).map(([k,x])=>k+' '+(x/f*100).toFixed(0)+'%').join(' '));
  console.log(m, t, (v / 1e6).toFixed(2) + 'm', (f / 1e3).toFixed(1) + 'k', ((f / v) * 100).toFixed(3) + '%', 'over', (f - e).toFixed(0));
}
